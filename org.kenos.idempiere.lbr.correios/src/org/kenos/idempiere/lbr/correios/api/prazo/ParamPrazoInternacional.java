package org.kenos.idempiere.lbr.correios.api.prazo;

public class ParamPrazoInternacional {
	
	private String coProduto = null;

	private String nuRequisicao = null;

	private String dtEvento = null;

	private String cepOrigem = null;

	private String sgPaisDestino = null;

	private String coCidadeDestino = null;

	public String getCoProduto() {
		return coProduto;
	}

	public void setCoProduto(String coProduto) {
		this.coProduto = coProduto;
	}

	public String getNuRequisicao() {
		return nuRequisicao;
	}

	public void setNuRequisicao(String nuRequisicao) {
		this.nuRequisicao = nuRequisicao;
	}

	public String getDtEvento() {
		return dtEvento;
	}

	public void setDtEvento(String dtEvento) {
		this.dtEvento = dtEvento;
	}

	public String getCepOrigem() {
		return cepOrigem;
	}

	public void setCepOrigem(String cepOrigem) {
		this.cepOrigem = cepOrigem;
	}

	public String getSgPaisDestino() {
		return sgPaisDestino;
	}

	public void setSgPaisDestino(String sgPaisDestino) {
		this.sgPaisDestino = sgPaisDestino;
	}

	public String getCoCidadeDestino() {
		return coCidadeDestino;
	}

	public void setCoCidadeDestino(String coCidadeDestino) {
		this.coCidadeDestino = coCidadeDestino;
	}

}
